/**
 * Generates the lab-facing mapping status document from the tables themselves,
 * so the document can never drift from what the system actually does.
 *
 *   pnpm --filter api rx:mapping-report
 *
 * The buckets and the rendered document are exported so tests can assert what
 * the lab actually receives, instead of re-deriving it and asserting the
 * re-derivation.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DEVICE_ROWS } from "../services/rx/catalog-map/devices.table.js";
import { MODIFICATION_ROWS } from "../services/rx/catalog-map/modifications.table.js";
import { ATTRIBUTE_ROWS } from "../services/rx/catalog-map/attributes.table.js";
import { GUARD_ROWS } from "../services/rx/catalog-map/resolvers/guard.js";
import { DEVICE_LABELS } from "../services/rx/catalog-map/index.js";

export const ALL = [...DEVICE_ROWS, ...MODIFICATION_ROWS, ...ATTRIBUTE_ROWS, ...GUARD_ROWS];

/**
 * The rows in one document bucket. `none` rows are a deliberate no-op (the
 * selection correctly emits no line item) — they are NOT a gap and must never
 * appear in the document, so no bucket can ever contain one.
 */
export const bucket = (status) => ALL.filter((r) => r.status === status);

// "default" is an internal placeholder, not something a lab owner can act on —
// show the device name instead. Only match[0] (the current form's wording) is
// shown; match[1]+ is legacy wizard wording that would just confuse the lab.
const deviceOf = (r) => (r.device ? DEVICE_LABELS[r.device] || r.device : "—");
const selectionOf = (r) => (r.match[0] === "default" ? deviceOf(r) : r.match[0]);

const line = (r) => `| ${deviceOf(r)} | ${selectionOf(r)} | ${r.code ?? "—"} | ${r.name} |`;

/** The full document, as written to docs/rx-forms/mapping-status.md. */
export function renderDoc() {
  return `# Rx → Seazona mapping status

Generated by \`pnpm rx:mapping-report\`. Do not edit by hand.

## Confirmed (${bucket("confirmed").length}) — no action needed

| Device | Doctor selects | Seazona code | Product |
|---|---|---|---|
${bucket("confirmed").map(line).join("\n")}

## Proposed (${bucket("proposed").length}) — please confirm or correct

These are strong matches, but the form does not capture enough to be certain.

| Device | Doctor selects | We propose | Product |
|---|---|---|---|
${bucket("proposed").map(line).join("\n")}

## Open (${bucket("open").length}) — we need your decision

Nothing here is sent to Seazona. Orders using these selections are held.

| Device | Doctor selects | Why it's open |
|---|---|---|
${bucket("open").map((r) => `| ${deviceOf(r)} | ${selectionOf(r)} | ${r.reason ?? r.name} |`).join("\n")}

## Orthodontic appliances — not yet mapped

This is the largest open decision on the list, and it is not a table because we
have not been able to propose even a first guess.

Your catalog carries roughly 36 orthodontic products — expanders, tandems and
twin blocks — that differ by retention, screw type, clasp and base material. The
Rx form captures all of those selections from the doctor, but we need you to
tell us which combination of answers corresponds to which product code. Until
you do, **every orthodontic order is held**: nothing orthodontic is sent to
Seazona, and no orthodontic product code is ever guessed.
`;
}

const OUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  // repo-relative, NOT cwd-relative — running this from the repo root used to
  // write the document outside the repo entirely.
  "../../../../docs/rx-forms/mapping-status.md"
);

/** Write the document. Only runs when this file is executed directly. */
export function writeDoc() {
  fs.writeFileSync(OUT, renderDoc());
  console.log(
    `[rx-mapping-report] wrote ${OUT} — ${bucket("confirmed").length} confirmed, ` +
      `${bucket("proposed").length} proposed, ${bucket("open").length} open`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writeDoc();
